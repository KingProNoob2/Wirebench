#!/usr/bin/env python3
"""Writes Sources/WirebenchCore/BuiltInProfiles.swift from Dirigo's Profiles.ini.

The app does not read Profiles.ini: the hardware profiles and the SystemCmd command list it needs are compiled in. This reads a copy of that
file (it is not part of this repository) and writes only what the port uses — the thread tables, memory sizes, constant limits and each profile's
command list, plus the command table itself — as Swift source.

    python3 tools/gen_profiles.py /path/to/Profiles.ini

`ProfilesParserTests` compares the result with the file when it is found next to the checkout, so a change in either shows up there.
"""
import re
import sys
from pathlib import Path

# The keys `ProfilesParser.buildProfile` reads. Anything else in the file (the menu's layout, stored-data sizes, a default menu image) is not used.
FIXED = {"BaseProfile", "Alias", "Default", "Cpu", "Threads", "SystemCommands", "ProgramDataSize",
         "IntRamDataSize", "LongRamDataSize", "FloatRamDataSize", "IntRomDataSize", "LongRomDataSize", "FloatRomDataSize",
         "EepromOffset", "EepromDataSize", "EepromWriteBlock",
         "DirectConstMin", "DirectConstMax", "ConstantDataTypes", "ConstantDataTypeAliases"}
THREAD = re.compile(r"^Thread\d+(Name|Interval|ProgramSize)$")


def swift_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(path, out):
    text = Path(path).read_bytes().decode("cp1250", errors="replace").replace("\r", "")
    sections, current = [], None
    for raw in text.split("\n"):
        line = raw.strip()
        if not line or line.startswith((";", "#")):
            continue
        if line.startswith("[") and line.endswith("]"):
            current = (line[1:-1], [])
            sections.append(current)
            continue
        if current is None or "=" not in line:
            continue
        key, value = line.split("=", 1)
        current[1].append((key.strip(), value.strip()))

    profiles = [(n, p) for n, p in sections if n != "@SystemCommands"]
    commands = [p for n, p in sections if n == "@SystemCommands"][0]

    lines = [
        "// Generated by tools/gen_profiles.py from Dirigo's Profiles.ini. Do not edit by hand.",
        "//",
        "// The hardware profiles and the SystemCmd command list, compiled in: the app does not read Profiles.ini. Only the keys the parser uses are here.",
        "",
        "enum BuiltInProfiles {",
        "    /// Each profile's own properties, in file order. `BaseProfile` is resolved by `ProfilesParser.database(sections:)`.",
        "    static let profiles: [(name: String, properties: [(String, String)])] = [",
    ]
    for name, pairs in profiles:
        kept = [(k, v) for k, v in pairs if k in FIXED or THREAD.match(k)]
        lines.append(f"        ({swift_string(name)}, [")
        for k, v in kept:
            lines.append(f"            ({swift_string(k)}, {swift_string(v)}),")
        lines.append("        ]),")
    lines += ["    ]", "", "    /// The command table: a mnemonic and its definition, as `SystemCmd` blocks store one in `DEFINITION`.",
              "    static let commands: [(mnemonic: String, definition: String)] = ["]
    for mnemonic, definition in commands:
        lines.append(f"        ({swift_string(mnemonic)}, {swift_string(re.sub(r'  +', ' ', definition.replace(chr(9), ' ')))}),")
    lines += ["    ]", "}", ""]
    Path(out).write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(profiles)} profiles, {len(commands)} commands -> {out}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1], Path(__file__).resolve().parent.parent / "Sources" / "WirebenchCore" / "BuiltInProfiles.swift")
