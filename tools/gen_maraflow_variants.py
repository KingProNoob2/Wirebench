#!/usr/bin/env python3
"""Generate the C++ variant enum from the Swift Maraflow definition table.

The Swift table is the single source for the definitions and their order; the C++ core receives the array index as
`WirebenchModuleDesc.variant`. Run from the Wirebench directory after editing MaraflowDefinitions.swift:

    python3 tools/gen_maraflow_variants.py --write
"""
import re
import sys

SWIFT = "Sources/WirebenchLibrary/MaraflowDefinitions.swift"
OUT = "Sources/WirebenchSimCxx/MaraflowVariants.h"


def ids():
    text = open(SWIFT, encoding="utf-8").read()
    return re.findall(r'makeDefinition\("([^"]+)"', text)


def header(all_ids):
    lines = [
        "// Generated by tools/gen_maraflow_variants.py from MaraflowDefinitions.swift.",
        "// Do not edit by hand. Each value is the index of the definition in MaraflowCatalog.all and is passed",
        "// to the core as WirebenchModuleDesc.variant.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "enum MaraflowVariant : int32_t {",
    ]
    for index, definition in enumerate(all_ids):
        name = "MARAFLOW_" + re.sub(r"[^A-Za-z0-9]+", "_", definition).strip("_")
        lines.append(f"    {name} = {index},")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    all_ids = ids()
    if not all_ids:
        sys.exit("no definitions found in " + SWIFT)
    text = header(all_ids)
    if "--write" in sys.argv:
        open(OUT, "w", encoding="utf-8").write(text)
        print(f"wrote {OUT} with {len(all_ids)} variants")
    else:
        print(text)
